const router = require('express').Router()
const rateLimit = require('express-rate-limit')
const c = require('./userController')
const { verifyUser } = require('../../middlewares/auth')
const { authorizeRoles } = require('../../middlewares/authorize')
const authLimit = rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, skip: () => process.env.NODE_ENV === 'test', standardHeaders: 'draft-7', legacyHeaders: false })
router.post('/register', authLimit, c.Register)
router.post('/login', authLimit, c.Login)
router.post('/logout', c.Logout)
router.get('/me', verifyUser, c.GetUser)
router.get('/users', verifyUser, authorizeRoles('admin'), c.GetAllUsers)
router.put('/users/:id', verifyUser, authorizeRoles('admin'), c.UpdateUser)
router.delete('/users/:id', verifyUser, authorizeRoles('admin'), c.DeleteUser)
module.exports = router
